/**
 * ✨ Upscale & improve is an OPT-IN, proved in the DOM rather than in a regex.
 *
 * One component (GeneratedImageLightbox) serves three surfaces and only two of
 * them may grow the button: the ◉ Canvas board and the checkpoint / run gallery
 * — the screen the improvement is actually delivered to — while a pill's preview
 * must gain nothing at all. A preview is a URL and a STEP held by a lineage
 * node: there is no library row to improve and no id to send, so a button there
 * would post a STEP as an image id.
 *
 * Source-text assertions (src/utils/canvasImprove.test.js) pin which host passes
 * what. They cannot see the thing that actually breaks: the improve group calls
 * `useCapabilities()`, which THROWS outside its provider, and the pill preview
 * renders in places that have no such provider around them. So this file mounts
 * the components (tests/support/mountJsx.mjs) and reads the markup that comes
 * out — including the host that must render nothing new, which is the half a
 * feature test never checks.
 */
import assert from 'node:assert/strict'
import test from 'node:test'

import { createElement, renderToStaticMarkup } from './support/mountJsx.mjs'

/* ⚠️ Dynamic — the hooks that teach Node to read .jsx are installed while
   mountJsx.mjs is evaluated, and a static import would already be linked. */
const { default: GeneratedImageLightbox } =
  await import('../src/components/shared/GeneratedImageLightbox.jsx')
const { default: PreviewLightbox } =
  await import('../src/components/dataset/PreviewLightbox.jsx')
const { default: CheckpointGalleryPanel } =
  await import('../src/components/shared/CheckpointGalleryPanel.jsx')
const { CapabilitiesProvider } = await import('../src/context/CapabilitiesContext.jsx')
const { ToastProvider } = await import('../src/components/common/Toast.jsx')

/** One row exactly as the galleries publish it (services.cloud_training
 *  ._gallery_image): the id is a `lora_test_image.id` and the dataset travels
 *  with it, which is the whole context the gallery needs to offer the pass. */
const row = (extra = {}) => ({
  id: 4211, dataset_id: 7, url: '/api/dataset/7/img/x.png', step: 2500,
  seed: 1234, prompt: 'a portrait', derivation_kind: null, ...extra,
})

/** The improve group probes capabilities, so it only ever renders inside the
 *  provider its hosts are mounted in. */
const inApp = (node) =>
  renderToStaticMarkup(createElement(ToastProvider, null,
    createElement(CapabilitiesProvider, null, node)))

const improveButtons = (html) => [...html.matchAll(/data-testid="lightbox-improve-([a-z0-9]+)"/g)]
  .map((m) => m[1])

test('the gallery lightbox, given what the panel passes, shows ✨ beside ⬇', () => {
  const html = inApp(createElement(GeneratedImageLightbox, {
    img: row(), alt: 'Generated by run 3', onClose: () => {},
    onImprove: () => {}, datasetId: 7,
  }))
  assert.deepEqual(improveButtons(html), ['klein'],
    'Klein is always offered; SeedVR2 only once it is installed')
  assert.match(html, /data-testid="lightbox-download"/, 'and Download is still there')
  // Klein's amber note no longer rides along inline — ✨ opens the shared
  // ImproveModal and the note is that modal's settings screen. The bare viewer
  // must therefore NOT carry the note's markers any more…
  assert.doesNotMatch(html, /data-testid="klein-improve-edit-toggle"/)
})

test("the modal ✨ opens carries Klein's note — pointers and the instruction editor", async () => {
  // …and the modal must. Its settings phase is the initial one, so a bare
  // render shows the note with the settings pointers AND the in-place
  // instruction editor — the branch most likely to throw on a bare render.
  // (The editor's own behaviour is covered by
  // tests/klein-improve-inline-editor.test.mjs; what is asserted here is that
  // the modal renders it at all, for the same host props the gallery passes.)
  const { default: ImproveModal } = await import('../src/components/shared/ImproveModal.jsx')
  const html = inApp(createElement(ImproveModal, {
    img: row(), host: 'library', datasetId: 7, subjectType: 'person', onClose: () => {},
  }))
  assert.match(html, /data-testid="improve-modal-generate"/)
  assert.match(html, /data-testid="klein-improve-edit-toggle"/)
  assert.match(html, /focus=identity-prompt-klein-improve/)
})

test('the same lightbox with NO handler renders no improve button at all', () => {
  // What a picture the board holds only as a URL gets, and what an already
  // improved row gets: the host passes `undefined`, and the group disappears —
  // the refusal is a missing button, not a 400 after the click.
  const html = inApp(createElement(GeneratedImageLightbox, {
    img: row({ derivation_kind: 'canvas_image_improve' }), alt: 'x', onClose: () => {},
  }))
  assert.deepEqual(improveButtons(html), [])
  assert.match(html, /data-testid="lightbox-download"/)
})

test('the pill preview gains NOTHING — no improve, no repair, no camera', () => {
  /* The viewer owns ✦ and 📷 now (lightbox-owns-the-verbs contract), so the
     proof moved from "a hook throws outside its provider" to the markup
     itself: a picture the host holds only as a URL has no library row, and a
     row-less picture gets NO verb — not improve (the host passes none), not
     ✦, not 📷 (the viewer's own hasRow gate). Mounted under the app's
     ToastProvider because the viewer's root legitimately uses the toast
     infrastructure; `useCapabilities` is still only reached through the
     improve group, which this host must never render. */
  const html = renderToStaticMarkup(createElement(ToastProvider, null,
    createElement(PreviewLightbox, {
      target: { url: '/api/dataset/7/img/p.png', step: 1500 }, onClose: () => {},
    })))
  assert.deepEqual(improveButtons(html), [])
  assert.doesNotMatch(html, /Improve via|Upscale via/)
  assert.doesNotMatch(html, /data-testid="lightbox-repair"/)
  assert.doesNotMatch(html, /data-testid="lightbox-camera-angles"/)
  assert.match(html, /data-testid="generated-image-lightbox"/, 'it still renders')
})

test('the gallery panel itself mounts with the shared handler wired in', () => {
  /* The hook the panel now calls uses `useToast()`, which THROWS outside its
     provider — and this panel has two hosts (the board and the dataset page's
     run graph). Executing it is what proves the wiring is reachable from a real
     mount rather than only from a regex. */
  const html = inApp(createElement(CheckpointGalleryPanel, {
    target: { kind: 'checkpoint', recordId: 3, step: 2500 }, onClose: () => {},
  }))
  assert.match(html, /data-testid="checkpoint-gallery-panel"/)
  assert.doesNotMatch(html, /NaN/)
})
